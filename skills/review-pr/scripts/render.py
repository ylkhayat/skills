#!/usr/bin/env python3
"""Render every artifact of a /review-pr round from one findings.json.

    render.py crit    <findings.json>   -> crit --file payload (inline + review-level)
    render.py body    <findings.json>   -> the GitHub review body (marker + Round badge)
    render.py payload <findings.json>   -> POST /pulls/<n>/reviews payload
    render.py event   <findings.json>   -> APPROVE | COMMENT  (read off the asks)
    render.py --selftest

Only crit bodies go out unmarked: crit is a private working document. `body` and
`payload` prefix the ai-ethics badge, because that text becomes public.

Hard errors (exit 1) are missing required fields. Length caps are warnings on
stderr — the reviewer sees them and decides.
"""
import json
import re
import sys
from urllib.parse import quote

MARKER = (
    "[![Generated by Claude Code](https://img.shields.io/badge/"
    "Generated%20by-Claude%20Code-D97757?logo=anthropic&logoColor=white)]"
    "(https://claude.com/claude-code)"
)
SEV = {
    "HIGH": "![HIGH](https://img.shields.io/badge/HIGH-b91c1c?style=flat-square)",
    "MEDIUM": "![MEDIUM](https://img.shields.io/badge/MEDIUM-d97706?style=flat-square)",
    "LOW": "![LOW](https://img.shields.io/badge/LOW-0969da?style=flat-square)",
    # SCOPE replaces a severity rather than sitting beside one: a scope note is not a
    # defect, so there is no HIGH to file. See review-exchange, "Scope".
    "SCOPE": "![scope](https://img.shields.io/badge/scope-0f766e?style=flat-square)",
    # DEAD is SCOPE's sibling: it replaces a severity too, because code with no
    # counterparty is not a defect with a consequence to grade. A dead guard that also
    # breaks something is a defect at its own severity, not a DEAD.
    "DEAD": "![dead](https://img.shields.io/badge/dead-86198f?style=flat-square)",
    # NORM: the code works and differs from a documented convention (house, ecosystem or
    # language). Advisory, so it replaces a severity too; a drift that breaks something or
    # opens a hole is a defect at its own severity. See review-exchange, "Norm".
    "NORM": "![norm](https://img.shields.io/badge/norm-4f46e5?style=flat-square)",
}
ASK = {
    "blocking": "![blocking](https://img.shields.io/badge/blocking-1f2328?style=flat-square)",
    "question": "![question](https://img.shields.io/badge/question-8250df?style=flat-square)",
    "non-blocking": "![non--blocking](https://img.shields.io/badge/non--blocking-6e7781?style=flat-square)",
}
CLAUDE = "D97757"
HUMAN = "6e7781"


def chip(label, message, color, logo=False):
    """A two-part shields badge. `-` and `_` are shields escapes, so double them first."""
    esc = lambda s: quote(s.replace("-", "--").replace("_", "__"), safe="@")
    alt = f"{label} {message}".replace("[", "").replace("]", "")
    tail = "&logo=anthropic&logoColor=white" if logo else ""
    return f"![{alt}](https://img.shields.io/badge/{esc(label)}-{esc(message)}-{color}?style=flat-square{tail})"


def provenance(f):
    """Who raised it, who agreed. Flagged is one value and always renders; endorsed is a list."""
    who = f.get("flagged_by") or "Claude Code"
    out = [chip("flagged", who, CLAUDE if who == "Claude Code" else HUMAN, logo=who == "Claude Code")]
    names = [n for n in (f.get("endorsed_by") or []) if n]
    if names:
        shown = names if len(names) <= 2 else names[:2] + [f"+{len(names) - 2}"]
        out.append(chip("endorsed", ", ".join(shown), HUMAN))
    return out


GLYPH = {"open": "●", "fixed": "✓", "answered": "↩", "theirs": "—"}
SEV_ORDER = {"HIGH": 0, "MEDIUM": 1, "LOW": 2, "NORM": 3, "DEAD": 4, "SCOPE": 5}
SHORT_SEV = {"HIGH": "HIGH", "MEDIUM": "MED", "LOW": "LOW", "NORM": "NORM", "DEAD": "DEAD", "SCOPE": "SCOPE"}

warnings = []


def warn(msg):
    warnings.append(msg)


def die(msg):
    print(f"render.py: {msg}", file=sys.stderr)
    sys.exit(1)


def sentences(text):
    """Rough sentence count. Abbreviations are not worth a parser here."""
    text = re.sub(r"`[^`]*`", "X", text or "")
    return len([s for s in re.split(r"(?<=[.!?])\s+", text.strip()) if s])


def round_badge(n):
    return f"![Round {n}](https://img.shields.io/badge/Round-{n}-1f2328?style=flat-square)"


# ---------------------------------------------------------------- validation

def load(path):
    with open(path) as fh:
        doc = json.load(fh)
    for key in ("pr", "owner", "repo", "round", "aidr"):
        if not doc.get(key):
            die(f"missing required top-level field: {key}")
    if sentences(doc["aidr"]) > 3:
        warn(f"AI;DR is {sentences(doc['aidr'])} sentences, cap is 3")
    for f in doc.get("findings", []):
        fid = f.get("id", "?")
        if f.get("reply_to") or f.get("status") == "theirs":
            continue  # a reply on someone else's thread has no shape of its own
        for key in ("path", "claim", "severity", "ask"):
            if not f.get(key):
                die(f"finding {fid}: missing {key}")
        if f["severity"] not in SEV:
            die(f"finding {fid}: severity {f['severity']!r} not in {list(SEV)}")
        if f["ask"] not in ASK:
            die(f"finding {fid}: ask {f['ask']!r} not in {list(ASK)}")
        if f["severity"] == "SCOPE" and f["ask"] != "non-blocking":
            die(f"finding {fid}: a SCOPE finding is always non-blocking, never {f['ask']!r}")
        if f["severity"] == "DEAD" and f["ask"] != "non-blocking":
            die(f"finding {fid}: a DEAD finding is always non-blocking, never {f['ask']!r}")
        if f["severity"] == "NORM" and f["ask"] != "non-blocking":
            die(f"finding {fid}: a NORM finding is always non-blocking, never {f['ask']!r}")
        # A norm without its source is an opinion (norms-lens.md): the rule in one line, and
        # the primary document that states it.
        if f["severity"] == "NORM" and not (f.get("norm") and str(f.get("source", "")).startswith("https://")):
            die(f"finding {fid}: a NORM finding needs `norm` (the rule, one line) and `source` (an https link to where it is written)")
        # The search IS the evidence (deletion-lens.md). "Looks unused" is rung 1, and a
        # deletion asserted without the command that found nothing is how the one caller
        # in another shard gets deleted.
        if f["severity"] == "DEAD" and not f.get("repro"):
            die(f"finding {fid}: a DEAD finding needs the search that found no counterparty in `repro`")
        why = f.get("why") or {}
        # A scope note lives entirely above the fold — an essay defending a nudge is the
        # thing the cap exists to prevent, so it is not warned for an empty toggle.
        for key in ("mechanism", "takeaway") if f["severity"] not in ("SCOPE", "DEAD", "NORM") else ():
            if not why.get(key):
                warn(f"finding {fid}: why.{key} is empty")
        above = sentences(f["claim"]) + sentences(f.get("failure", ""))
        if above > 3:
            warn(f"finding {fid}: {above} sentences above the fold, cap is 3 — move the rest to why.detail")
        if not f.get("failure"):
            warn(f"finding {fid}: no failure/evidence line — is this a finding or a question?")
        if f["severity"] == "HIGH" and not f.get("repro") and not why.get("not_verified"):
            warn(f"finding {fid}: HIGH with no repro and no why.not_verified — rung 2 HIGH")
    return doc


# ---------------------------------------------------------------- rendering

def finding_body(f):
    """The comment shape. Three sentences above the fold, the rest in Why."""
    if f.get("reply_to"):
        return f["claim"]  # endorsed / not endorsed replies are one or two lines, verbatim
    badges = [SEV[f["severity"]], ASK[f["ask"]]] + provenance(f)
    out = [" ".join(badges) + f" **{f['claim']}**"]
    if f.get("failure"):
        out += ["", f["failure"]]
    tail = []
    if f.get("fix"):
        # a scope note has no fix — it has somewhere else to live
        label = {"SCOPE": "Home", "DEAD": "Delete", "NORM": "Align"}.get(f["severity"], "Fix")
        tail.append(f"{label}: {f['fix']}")
    if f.get("norm"):
        # two fixed lines Concierge reads back for its Norms view: keep their shape
        tail += [f"Norm: {f['norm']}", f"Source: <{f['source']}>"]
    if f.get("drops_with"):
        tail.append("Drops with it: " + ", ".join(f"`{d}`" for d in f["drops_with"]))
    if f.get("repro"):
        tail.append(f"Repro: {f['repro']}")
    if tail:
        out += [""] + tail
    why = f.get("why") or {}
    labels = [
        ("Mechanism", why.get("mechanism")),
        ("Detail", why.get("detail")),
        ("Takeaway", why.get("takeaway")),
        ("Not verified", why.get("not_verified")),
    ]
    # Blank lines between them: GFM joins adjacent lines into one paragraph, which
    # would run Mechanism, Detail and Takeaway together on a single line.
    blocks = [f"**{label}** — {val}" for label, val in labels if val]
    if blocks:
        out += ["", "<details><summary>Why</summary>", ""]
        out += "\n\n".join(blocks).split("\n")
        out += ["</details>"]
    return "\n".join(out)


def ledger(doc):
    rows = ["| | Where | Claim |", "|---|---|---|"]
    live = [f for f in doc.get("findings", []) if not f.get("reply_to")]
    live.sort(key=lambda f: (SEV_ORDER.get(f.get("severity"), 9), f.get("path", "")))
    for f in live[:8]:
        anchor = f"{f['path'].split('/')[-1]}:{f.get('line', '')}"
        where = f"[`{anchor}`]({f['thread_url']})" if f.get("thread_url") else f"`{anchor}`"
        glyph = GLYPH.get(f.get("status", "open"), GLYPH["open"])
        rows.append(f"| {glyph} {SHORT_SEV[f['severity']]} {f['ask']} | {where} | {f['claim']} |")
    if len(live) > 8:
        rows.append(f"| | | +{len(live) - 8} more in the threads below |")
    return "\n".join(rows)


def meta_line(doc):
    m = doc.get("meta") or {}
    live = [f for f in doc.get("findings", []) if not f.get("reply_to")]
    bits = []
    if doc.get("ticket"):
        bits.append(f"`{doc['ticket']} · {doc.get('verdict', 'Follows')}`")
    if m.get("files"):
        bits.append(f"{m['files']} files")
    bits.append(f"{sum(1 for f in live if f.get('status', 'open') == 'open')} open")
    fixed = sum(1 for f in live if f.get("status") == "fixed")
    if fixed:
        bits.append(f"{fixed} fixed")
    if m.get("rung"):
        bits.append(f"rung {m['rung']}")
    if m.get("didnt_run"):
        bits.append(f"didn't run: {m['didnt_run']}")
    return " · ".join(bits)


def body(doc, marked=True):
    out = []
    if marked:
        out += [MARKER, round_badge(doc["round"]), ""]
    out.append(f"**AI;DR** — {doc['aidr']}")
    if doc.get("reviewer_note"):
        out += ["", "**Reviewer note**", f"> {doc['reviewer_note']}"]
    out += ["", meta_line(doc)]
    if any(not f.get("reply_to") for f in doc.get("findings", [])):
        out += ["", ledger(doc)]
    if doc.get("takeaway"):
        out += ["", f"**Takeaway** — {doc['takeaway']}"]
    if doc.get("on_others"):
        out += ["", doc["on_others"]]
    if doc.get("gif") and event(doc) == "APPROVE":
        word = doc.get("gif_word", "ship it")
        out += ["", f'<img src="{doc["gif"]}" width="200"><br><sub><b>{word}</b></sub>']
    return "\n".join(out)


def event(doc):
    """Read off the ask, never the severity. Three pull-backs stay judgement calls."""
    open_asks = {
        f["ask"] for f in doc.get("findings", [])
        if not f.get("reply_to") and f.get("status", "open") == "open"
    }
    if open_asks & {"blocking", "question"}:
        return "COMMENT"
    if doc.get("verdict") == "Contradicts" or doc.get("force_comment"):
        return "COMMENT"
    return "APPROVE"


def crit_payload(doc):
    entries = [{"body": body(doc, marked=False)}]
    for f in doc.get("findings", []):
        e = {"body": finding_body(f)}
        if f.get("reply_to"):
            e["reply_to"] = f["reply_to"]  # a reply needs no anchor of its own
        else:
            e["file"] = f["path"]
            e["line"] = f"{f['start_line']}-{f['line']}" if f.get("start_line") else f.get("line")
        entries.append(e)
    return entries


def gh_payload(doc):
    comments = []
    for f in doc.get("findings", []):
        if f.get("reply_to"):
            continue  # replies go to /comments/<id>/replies, never into a review payload
        if not f.get("line"):
            die(f"finding {f.get('id')}: file-scope comment has no line — re-anchor it or fold it into the body")
        c = {"path": f["path"], "side": "RIGHT",
             "body": MARKER + "\n\n" + finding_body(f)}
        if f.get("start_line"):
            c["start_line"] = f["start_line"]
            c["start_side"] = "RIGHT"
        c["line"] = f["line"]
        comments.append(c)
    return {"event": event(doc), "body": body(doc), "comments": comments}


# ---------------------------------------------------------------- selftest

def selftest():
    doc = {
        "pr": 1, "owner": "o", "repo": "r", "round": 2, "ticket": "ENG-1",
        "verdict": "Follows", "aidr": "One. Two.", "meta": {"files": 3, "rung": 4},
        "findings": [
            {"id": "f1", "path": "a/b.ts", "line": 10, "severity": "LOW",
             "ask": "non-blocking", "status": "open", "claim": "Claim one.",
             "failure": "It breaks.", "fix": "do x",
             "why": {"mechanism": "m", "takeaway": "t"}},
            {"id": "f2", "path": "a/b.ts", "line": 20, "severity": "HIGH",
             "ask": "blocking", "status": "fixed", "claim": "Claim two.",
             "failure": "It breaks worse.", "repro": "cmd -> red",
             "why": {"mechanism": "m", "detail": "d", "takeaway": "t"}},
        ],
    }
    b = body(doc)
    lines = b.split("\n")
    assert lines[0] == MARKER, "marker is not line 1"
    assert lines[1] == round_badge(2), "Round badge is not line 2"
    assert "Round-2" in lines[1]
    assert event(doc) == "APPROVE", "no open blocking/question -> APPROVE"
    doc["findings"][1]["status"] = "open"
    assert event(doc) == "COMMENT", "open blocking -> COMMENT"
    doc["findings"][1]["status"] = "fixed"
    doc["verdict"] = "Contradicts"
    assert event(doc) == "COMMENT", "Contradicts pulls back to COMMENT"
    doc["verdict"] = "Follows"
    # ledger: most severe first, glyph rides in the first cell
    rows = [r for r in ledger(doc).split("\n")[2:]]
    assert rows[0].startswith("| ✓ HIGH blocking |"), rows[0]
    assert rows[1].startswith("| ● LOW non-blocking |"), rows[1]
    # a reply record carries no anchor and no shape
    doc["findings"].append({"id": "f3", "reply_to": "c-1", "claim": "Endorsed — and also at x.ts:9."})
    cp = crit_payload(doc)
    assert cp[-1] == {"body": "Endorsed — and also at x.ts:9.", "reply_to": "c-1"}, cp[-1]
    assert len(gh_payload(doc)["comments"]) == 2, "replies never enter a review payload"
    assert len(ledger(doc).split("\n")) == 4, "replies never enter the ledger"
    # crit bodies unmarked, gh bodies marked
    assert MARKER not in crit_payload(doc)[0]["body"], "crit must stay unmarked"
    p = gh_payload(doc)
    assert all(c["body"].startswith(MARKER) for c in p["comments"]), "every posted comment is marked"
    assert p["body"].startswith(MARKER)
    assert len(p["comments"]) == 2
    # shape
    fb = finding_body(doc["findings"][1])
    assert fb.split("\n")[0].startswith(SEV["HIGH"] + " " + ASK["blocking"] + " ")
    assert fb.split("\n")[0].endswith("**Claim two.**")
    # provenance: flagged always, defaulting to Claude Code; endorsed only when there is one
    assert chip("flagged", "Claude Code", CLAUDE, logo=True) in fb, "flagged badge missing"
    assert "endorsed" not in fb, "no endorsers -> no endorsed badge"
    doc["findings"][1]["flagged_by"] = "@ylkhayat"
    doc["findings"][1]["endorsed_by"] = ["Claude Code", "cursor[bot]", "@nikolai"]
    fb = finding_body(doc["findings"][1])
    assert chip("flagged", "@ylkhayat", HUMAN) in fb, "human flagger is not orange"
    assert "endorsed-Claude%20Code%2C%20cursor%5Bbot%5D%2C%20%2B1-" in fb, fb.split("\n")[0]
    assert "[bot]]" not in fb, "unescaped bracket in alt text breaks the markdown image"
    doc["findings"][1].pop("flagged_by"), doc["findings"][1].pop("endorsed_by")
    assert "<details><summary>Why</summary>" in fb
    assert "**Detail** — d" in fb
    assert "**Mechanism** — m\n\n**Detail** — d\n\n**Takeaway** — t" in fb, "why labels need blank lines or GFM runs them together"
    assert "Fix:" not in fb, "no fix given -> no empty label"
    # ---- DEAD: the deletion that carries its own search
    ddoc = {
        "pr": 1, "owner": "o", "repo": "r", "round": 1, "aidr": "One.",
        "findings": [
            {"id": "d1", "path": "lib/callDenial.ts", "line": 142, "severity": "DEAD",
             "ask": "non-blocking", "status": "open",
             "claim": "`isHandledCallDenial` has zero production call sites.",
             "failure": "The definition and nine test assertions, nothing else.",
             "fix": "the export, its docblock and its test block",
             "repro": "grep -rn isHandledCallDenial src/ | grep -v '\\.test\\.' -> 1 line"},
        ],
    }
    db = finding_body(ddoc["findings"][0])
    assert db.split("\n")[0].startswith(SEV["DEAD"] + " " + ASK["non-blocking"] + " "), db
    assert not any(SEV[k] in db for k in ("HIGH", "MEDIUM", "LOW", "SCOPE")), "DEAD replaces the severity"
    assert "Delete: the export" in db, "a DEAD finding deletes, it does not fix"
    assert "Fix:" not in db and "Home:" not in db, db
    assert event(ddoc) == "APPROVE", "a deletion never withholds approval"
    assert SEV_ORDER["DEAD"] < SEV_ORDER["SCOPE"], "DEAD sorts above SCOPE, below LOW"
    # the two refusals: an escalated ask, and a deletion with no search behind it
    import contextlib as _c, io as _io, json as _j, tempfile as _t
    for mutate, why in ((lambda d: d["findings"][0].update(ask="blocking"), "escalated DEAD"),
                        (lambda d: d["findings"][0].pop("repro"), "DEAD with no grep")):
        bad = _j.loads(_j.dumps(ddoc)); mutate(bad)
        fh = _t.NamedTemporaryFile("w", suffix=".json", delete=False)
        _j.dump(bad, fh); fh.close()
        err = _io.StringIO()
        try:
            with _c.redirect_stderr(err):
                load(fh.name)
        except SystemExit:
            pass
        else:
            raise AssertionError(f"{why} must not render")
    # ---- NORM: the drift that carries its source
    ndoc = {
        "pr": 1, "owner": "o", "repo": "r", "round": 1, "aidr": "One.",
        "findings": [
            {"id": "n1", "path": "src/Today.tsx", "line": 42, "severity": "NORM",
             "ask": "non-blocking", "status": "open",
             "claim": "State derived in an effect renders twice.",
             "fix": "compute it during render",
             "norm": "Don't use an effect to derive state from props or state",
             "source": "https://react.dev/learn/you-might-not-need-an-effect"},
        ],
    }
    nb = finding_body(ndoc["findings"][0])
    assert nb.split("\n")[0].startswith(SEV["NORM"] + " " + ASK["non-blocking"] + " "), nb
    assert "Align: compute it during render" in nb and "Fix:" not in nb, nb
    assert "Norm: Don't use an effect" in nb and "Source: <https://react.dev/" in nb, nb
    assert event(ndoc) == "APPROVE", "a drift never withholds approval"
    assert SEV_ORDER["LOW"] < SEV_ORDER["NORM"] < SEV_ORDER["DEAD"], "NORM sorts below LOW, above DEAD"
    for mutate, why in ((lambda d: d["findings"][0].update(ask="blocking"), "escalated NORM"),
                        (lambda d: d["findings"][0].pop("source"), "NORM with no source"),
                        (lambda d: d["findings"][0].update(source="react.dev"), "NORM with a bare source")):
        bad = _j.loads(_j.dumps(ndoc)); mutate(bad)
        fh = _t.NamedTemporaryFile("w", suffix=".json", delete=False)
        _j.dump(bad, fh); fh.close()
        try:
            with _c.redirect_stderr(_io.StringIO()):
                load(fh.name)
        except SystemExit:
            pass
        else:
            raise AssertionError(f"{why} must not render")
    # ---- SCOPE: the nudge that cannot be escalated
    sdoc = {
        "pr": 1, "owner": "o", "repo": "r", "round": 1, "aidr": "One.",
        "findings": [
            {"id": "s1", "path": "h/useDebounce.ts", "line": 1, "severity": "SCOPE",
             "ask": "non-blocking", "status": "open", "claim": "Nothing in this PR calls it.",
             "failure": "Added alongside the search box, never called.",
             "fix": "its own PR, or the follow-up that needs it",
             "drops_with": ["h/index.ts:12", "h/useDebounce.test.ts"]},
            {"id": "s2", "path": "a/b.ts", "line": 9, "severity": "HIGH", "ask": "blocking",
             "status": "fixed", "claim": "C.", "failure": "F.", "repro": "cmd -> red",
             "why": {"mechanism": "m", "takeaway": "t"}},
        ],
    }
    sb = finding_body(sdoc["findings"][0])
    assert sb.split("\n")[0].startswith(SEV["SCOPE"] + " " + ASK["non-blocking"] + " "), sb
    assert not any(SEV[k] in sb for k in ("HIGH", "MEDIUM", "LOW")), "SCOPE replaces the severity"
    assert "Home: its own PR" in sb, "a scope note has a home, not a fix"
    assert "Drops with it: `h/index.ts:12`, `h/useDebounce.test.ts`" in sb, sb
    assert "<details>" not in sb, "a nudge that needs a toggle is an essay"
    assert ledger(sdoc).split("\n")[-1].startswith("| ● SCOPE non-blocking |"), "SCOPE sorts last"
    assert event(sdoc) == "APPROVE", "a scope note never withholds approval"
    # ask is not a field the author of a findings.json gets to choose here
    import contextlib, io, os, tempfile
    sdoc["findings"][0]["ask"] = "blocking"
    fh = tempfile.NamedTemporaryFile("w", suffix=".json", delete=False)
    json.dump(sdoc, fh), fh.close()
    err = io.StringIO()
    try:
        with contextlib.redirect_stderr(err):
            load(fh.name)
        raise AssertionError("a blocking SCOPE finding must not render")
    except SystemExit:
        assert "always non-blocking" in err.getvalue(), err.getvalue()
    finally:
        os.unlink(fh.name)

    # The badge literals live in the shared contract; this file is their implementation.
    # An edit to the contract that does not reach here is the drift this check exists to catch.
    import os
    # The contract is the sibling skill, wherever this bundle is installed.
    here = os.path.dirname(os.path.abspath(__file__))
    contract = os.path.join(here, "..", "..", "review-exchange", "SKILL.md")
    if os.path.exists(contract):
        text = open(contract).read()
        pairs = list(SEV.items()) + list(ASK.items()) + [
            ("flagged", chip("flagged", "Claude Code", CLAUDE, logo=True)),
            ("endorsed", chip("endorsed", "@ylkhayat, cursor[bot]", HUMAN)),
        ]
        for label, markdown in pairs:
            assert markdown in text, f"{label} badge differs from review-exchange/SKILL.md"
        print(f"contract OK  ({len(pairs)} badges match review-exchange)")

    # the caps are counted, not guessed
    assert sentences("One. Two. Three.") == 3
    assert sentences("Only `a.b(); c.d()` here.") == 1, "code spans are not sentence breaks"
    print("selftest OK")


def main():
    if len(sys.argv) > 1 and sys.argv[1] == "--selftest":
        return selftest()
    if len(sys.argv) != 3:
        die(__doc__)
    cmd, path = sys.argv[1], sys.argv[2]
    doc = load(path)
    out = {
        "crit": lambda: json.dumps(crit_payload(doc), indent=1),
        "body": lambda: body(doc),
        "payload": lambda: json.dumps(gh_payload(doc), indent=1),
        "event": lambda: event(doc),
    }.get(cmd)
    if not out:
        die(f"unknown command {cmd!r}")
    print(out())
    for w in warnings:
        print(f"render.py: warn: {w}", file=sys.stderr)


if __name__ == "__main__":
    main()
